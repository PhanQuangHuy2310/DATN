"""Generate web_client/src/catalogV2.js from api_core/catalog/catalog_v2.json.

The web image only contains web_client/, so the UI keeps a generated copy;
tests/test_request_catalog_v2.py fails when the two drift apart.
Usage: python scripts/generate_catalog_js.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "api_core/catalog/catalog_v2.json"
TARGET = ROOT / "web_client/src/catalogV2.js"


def render() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    groups = [{"code": g["code"], "label": g["label"]} for g in data["groups"]]
    items = [
        {
            "code": i["code"],
            "name": i["name"],
            "category": i["category"],
            "status": i["status"],
            "risk_weight": i["risk_weight"],
            "approval_level": i["approval_level"],
            "lifecycle": i["lifecycle"],
            "approval_route": i["approval_route"],
        }
        for i in data["items"]
    ]
    dump = lambda v: json.dumps(v, ensure_ascii=False, indent=2)
    return (
        "// GENERATED by scripts/generate_catalog_js.py from api_core/catalog/catalog_v2.json.\n"
        "// Do not edit by hand.\n"
        f"export const CATALOG_GROUPS = Object.freeze({dump(groups)});\n\n"
        f"export const CATALOG_ITEMS = Object.freeze({dump(items)});\n\n"
        "export const CATEGORY_LABELS = Object.freeze(Object.fromEntries(CATALOG_GROUPS.map((g) => [g.code, g.label])));\n"
        "export const catalogTypeNames = Object.fromEntries(CATALOG_ITEMS.map((i) => [i.code, i.name]));\n"
        "export const catalogTypeLevels = Object.fromEntries(CATALOG_ITEMS.map((i) => [i.code, { risk_weight: i.risk_weight, approval_level: i.approval_level }]));\n"
    )


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
